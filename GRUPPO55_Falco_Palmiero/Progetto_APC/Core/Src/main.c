static void DWT_Init(void)
{
  CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
  DWT->CYCCNT = 0;
  DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
}

static void delay_us(uint32_t us)
{
  uint32_t start = DWT->CYCCNT;
  uint32_t ticks = us * (SystemCoreClock / 1000000);
  while ((DWT->CYCCNT - start) < ticks);
}

void HCSR04_Trigger(void)
{
  HAL_GPIO_WritePin(HCSR04_TRIG_GPIO_Port, HCSR04_TRIG_Pin, GPIO_PIN_RESET);
  delay_us(2);
  HAL_GPIO_WritePin(HCSR04_TRIG_GPIO_Port, HCSR04_TRIG_Pin, GPIO_PIN_SET);
  delay_us(10);
  HAL_GPIO_WritePin(HCSR04_TRIG_GPIO_Port, HCSR04_TRIG_Pin, GPIO_PIN_RESET);
}
// servo motore :
void Servo_SetAngle(uint8_t angle)
{
  // Mappa 0-180 gradi in 500-2500 microsecondi (datasheet SG90)
  uint32_t pulse = 500 + ((uint32_t)angle * 2000) / 180;
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, pulse);
}

static void Avanza_Angolo(void)
{
  angolo_corrente += direzione * PASSO_ANGOLO;
  if (angolo_corrente >= 180) { angolo_corrente = 180; direzione = -1; }
  if (angolo_corrente <= 0)   { angolo_corrente = 0;   direzione = 1;  }
  Servo_SetAngle((uint8_t)angolo_corrente);
}


